def _remove_paragraph(paragraph: Paragraph) -> None:
    p = paragraph._element  # noqa: SLF001
    p.getparent().remove(p)


def _insert_after(paragraph: Paragraph, text: str, *, style_name: str) -> Paragraph:
    new_p = OxmlElement("w:p")
    paragraph._element.addnext(new_p)  # noqa: SLF001
    new_par = Paragraph(new_p, paragraph._parent)  # noqa: SLF001
    new_par.add_run(text)
    new_par.style = style_name
    return new_par


def main() -> None:
    if not DOC_PATH.exists():
        raise SystemExit(f"Не найден файл: {DOC_PATH}")

    doc = Document(str(DOC_PATH))
    ps = doc.paragraphs

    # Find anchors in the *body* (second occurrence: table of contents first, body second).
    def find_all_starts(prefix: str) -> list[int]:
        return [
            i for i, p in enumerate(doc.paragraphs) if (p.text or "").strip().startswith(prefix)
        ]

    def find_all_contains(term: str) -> list[int]:
        return [i for i, p in enumerate(doc.paragraphs) if term in (p.text or "")]

    ch2_idxs = find_all_contains("Глава 2")
    ch3_idxs = find_all_contains("Глава 3")
    if len(ch2_idxs) < 2 or len(ch3_idxs) < 2:
        raise SystemExit("Не удалось найти главы 2 и 3 (ожидались в содержании и в тексте).")

    body_ch2 = ch2_idxs[-1]
    body_ch3 = ch3_idxs[-1]

    # End boundary: "Список литературы" (body occurrence)
    lit_idxs = [
        i for i, p in enumerate(doc.paragraphs) if (p.text or "").strip() == "Список литературы"
    ]
    if len(lit_idxs) < 2:
        lit_idxs = [
            i for i, p in enumerate(doc.paragraphs) if "Список литературы" in (p.text or "")
        ]
    if len(lit_idxs) < 2:
        raise SystemExit("Не найден заголовок «Список литературы» в тексте (второе вхождение).")
    body_lit = lit_idxs[-1]

    if not (body_ch2 < body_ch3 < body_lit):
        raise SystemExit("Неверные границы глав (проверьте структуру документа).")

    # Use the same style as chapter headings in this document.
    style_name = doc.paragraphs[body_ch2].style.name

    # Remove everything between chapter 2 heading (exclusive) and literature heading (exclusive).
    # Keep "Глава 2..." paragraph itself and keep "Список литературы" heading.
    ps = doc.paragraphs
    for i in range(body_lit - 1, body_ch2, -1):
        _remove_paragraph(ps[i])

    # Refresh list after deletions
    ps = doc.paragraphs

    # Re-find the body Chapter 2 heading (it is kept)
    body_ch2 = find_all_contains("Глава 2")[-1]

    # Insert new text after body chapter 2 heading paragraph.
    anchor = ps[body_ch2]
    cursor = anchor

    for line in CH2_CH3_TEXT.splitlines():
        s = line.rstrip()
        if not s:
            continue

        # Skip the first chapter heading from the inserted text because the document already
        # contains the body "Глава 2..." heading paragraph we keep as an anchor.
        if s.lstrip().startswith("# Глава 2.") or s.lstrip().startswith("Глава 2."):
            continue

        # Skip markdown separators.
        if s.strip() == "---":
            continue

        # Strip markdown heading markers
        if s.startswith("# "):
            s = s[2:].strip()
        elif s.startswith("## "):
            s = s[3:].strip()

        # Minimal markdown normalization for Word:
        # - Bold-only lines: **text**
        # - Code-only lines: `command ...`
        bold_line = False
        code_line = False
        raw = s.strip()
        if raw.startswith("**") and raw.endswith("**") and len(raw) >= 4:
            bold_line = True
            s = raw[2:-2].strip()
        elif raw.startswith("`") and raw.endswith("`") and len(raw) >= 2:
            code_line = True
            s = raw[1:-1]

        # Remove inline backticks (keep plain text). Full code-line is handled above.
        if "`" in s and not code_line:
            s = s.replace("`", "")

        cursor = _insert_after(cursor, s, style_name=style_name)
        if bold_line:
            for r in cursor.runs:
                r.bold = True
        if code_line:
            for r in cursor.runs:
                r.font.name = "Consolas"

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(OUT_PATH))
    print(f"Готово: {OUT_PATH}")


if __name__ == "__main__":
    main()
