def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Generate a Russian diploma-style report (DOCX) for the CRM/SRM service-center project."
    )
    p.add_argument("--out", type=Path, default=Path("docs/Пояснительная_записка_CRM_SRM.docx"))
    p.add_argument("--access-date", type=str, default=date.today().isoformat())
    return p.parse_args()


def _set_base_styles(doc) -> None:
    """Set base formatting close to common Russian diploma requirements."""

    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Cm, Pt

    section = doc.sections[0]
    section.left_margin = Cm(2.0)
    section.right_margin = Cm(2.0)
    section.top_margin = Cm(2.0)
    section.bottom_margin = Cm(2.0)

    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(14)
    p = style.paragraph_format
    p.line_spacing = 1.5
    p.space_after = Pt(0)
    p.first_line_indent = Cm(1.25)
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    # Headings: keep readable and closer to formal style
    for name, size, bold in [
        ("Heading 1", 16, True),
        ("Heading 2", 15, True),
        ("Heading 3", 14, True),
    ]:
        st = doc.styles[name]
        st.font.name = "Times New Roman"
        st.font.size = Pt(size)
        st.font.bold = bold
        st.paragraph_format.first_line_indent = Cm(0)
        st.paragraph_format.space_before = Pt(10)
        st.paragraph_format.space_after = Pt(6)


def _add_par(doc, text: str) -> None:
    p = doc.add_paragraph(text.strip())
    # Ensure indent is consistent for added paragraphs even if styles differ in some Word installs
    from docx.shared import Cm

    if p.paragraph_format.first_line_indent is None:
        p.paragraph_format.first_line_indent = Cm(1.25)


def _add_bullets(doc, items: list[str]) -> None:
    for it in items:
        doc.add_paragraph(it.strip(), style="List Bullet")


def _add_table(doc, rows: list[list[str]]) -> None:
    if not rows:
        return
    table = doc.add_table(rows=1, cols=len(rows[0]))
    table.style = "Table Grid"
    for j, cell in enumerate(table.rows[0].cells):
        cell.text = rows[0][j]
    for r in rows[1:]:
        row_cells = table.add_row().cells
        for j, v in enumerate(r):
            row_cells[j].text = v


def _add_figure_placeholder(doc, title: str, description: str) -> None:
    doc.add_paragraph(f"Рисунок — {title}", style="List Number")
    doc.add_paragraph("[МЕСТО ДЛЯ СКРИНШОТА/РИСУНКА]")
    doc.add_paragraph(f"Описание: {description}")


